#!/usr/bin/env python3
"""Table of metadata sources for full SP3 (tracker item C3).

Joins the artifact's SP3 case files (data/raw/policy_reports/<b>/sp3_cases.csv)
with evaluation/coverage/sp3_metadata_sources.json, which records for each
field what the registry port of that boundary does. Fails if a case of the
artifact has no record or a record names a case that does not exist, so the
table cannot silently drift from the artifact's list.
"""

import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path

NAMES = {"ffmpeg_libvpx": "ffmpeg/libvpx", "magick_libpng": "magick/libpng",
         "memcached_bipbuffer": "memcached/bipbuffer", "memcached_hash": "memcached/hash",
         "nginx_libpcre": "nginx/libpcre", "nginx_openssl": "nginx/openssl",
         "rsync_popt": "rsync/popt", "ucl_libucl": "ucl/libucl",
         "yaml_libyaml": "yaml/libyaml", "zip_libzip": "zip/libzip"}
DOMAIN = {"U_only": "U", "U_or_null": "U", "T_only": "T", "T_or_null": "T",
          "T_or_U": "T or U", "T_or_U_or_null": "T or U", "unknown": "unknown"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact-reports", required=True, type=Path,
                        help="interspec-artifact data/raw/policy_reports")
    parser.add_argument("--records", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    records = json.loads(args.records.read_text())
    without = records["boundaries_without_fields"]

    cases = {}
    for benchmark in NAMES:
        path = args.artifact_reports / benchmark / "sp3_cases.csv"
        if benchmark in without or not path.exists():
            continue
        for row in csv.DictReader(path.open()):
            key = "|".join([row["function"], row["binding_kind"], row["binding_id"],
                            row["slot_path"]])
            if (benchmark, key) in cases:
                sys.exit(f"duplicate case {benchmark} {key}")
            cases[(benchmark, key)] = row

    rows, seen, errors = [], set(), []
    for record in records["fields"]:
        benchmark, key = record["benchmark"], record["key"]
        if record.get("origin") == "port":
            domain, origin, types = record["expected_domain"], "port only", ""
        else:
            case = cases.get((benchmark, key))
            if case is None:
                errors.append(f"record without a case in the artifact: {benchmark} {key}")
                continue
            seen.add((benchmark, key))
            domain = DOMAIN[case["sp3_target_class"]]
            origin, types = "artifact case file", case["slot_types"]
        rows.append({"boundary": NAMES[benchmark], "field": key, "listed_in": origin,
                     "c_type": types, "expected_domain": domain,
                     "checked_by_port": record["checked_by_port"],
                     "type_source": record["type_source"],
                     "bounds_source": record["bounds_source"],
                     "where": record["where"], "note": record["note"]})
    for benchmark, key in sorted(set(cases) - seen):
        errors.append(f"case of the artifact without a record: {benchmark} {key}")
    if errors:
        sys.exit("\n".join(errors))

    args.out.mkdir(parents=True)
    columns = list(rows[0])
    with (args.out / "sp3_metadata_sources.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        writer.writerows(rows)

    in_file = Counter(r["boundary"] for r in rows if r["listed_in"] == "artifact case file")
    port_only = Counter(r["boundary"] for r in rows if r["listed_in"] == "port only")
    checked = Counter(r["boundary"] for r in rows if r["checked_by_port"] == "yes")
    lines = ["# Metadata sources for full SP3", "",
             "Generated by `tools/render_sp3_metadata_table.py` from the artifact's",
             "`sp3_cases.csv` files and `evaluation/coverage/sp3_metadata_sources.json`.", "",
             "## Counts", "",
             "| Boundary | Paper: SP3 | Paper: unknown | Artifact case file | Checked by the port | Checked, not in the case file |",
             "|---|---:|---:|---:|---:|---:|"]
    totals = Counter()
    for benchmark, name in NAMES.items():
        paper = records["paper_sp3_counts"][benchmark]
        unknown = records["paper_unknown_counts"].get(benchmark, 0)
        listed = in_file[name] if benchmark not in without else "196 rows"
        lines.append(f"| {name} | {paper} | {unknown} | {listed} | {checked[name]} | "
                     f"{port_only[name]} |")
        totals.update(paper=paper, unknown=unknown, checked=checked[name],
                      port_only=port_only[name],
                      listed=in_file[name] if benchmark not in without else 0)
    lines.append(f"| Total | {totals['paper']} | {totals['unknown']} | {totals['listed']} "
                 f"(without nginx/openssl) | {totals['checked']} | {totals['port_only']} |")
    lines += ["", "## Fields", "",
              "| Boundary | Field | Listed in | Expected domain | Checked by the port | Type from | Bounds from | Note |",
              "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['boundary']} | `{r['field'].replace('|', ' / ')}` | {r['listed_in']} | "
                     f"{r['expected_domain']} | {r['checked_by_port']} | {r['type_source']} | "
                     f"{r['bounds_source']} | {r['note']} |")
    lines += ["", "## Boundaries whose case file is not joined", ""]
    for benchmark, text in without.items():
        lines.append(f"- **{NAMES[benchmark]}**: {text}")
    sources = Counter(r["type_source"] for r in rows if r["checked_by_port"] == "yes")
    lines += ["", "## Type source of the fields a port checks", ""]
    lines += [f"- {name}: {count}" for name, count in sorted(sources.items())]
    (args.out / "SP3_METADATA_SOURCES.md").write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} fields; {sum(checked.values())} checked by a port; "
          f"type sources {dict(sources)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
